/**
 * CalculiX deck writer.
 *
 * CalculiX reads the Abaqus input dialect, so this writer emits a deck that is
 * also a valid Abaqus deck for the same model — which is what makes the two
 * backends comparable: identical sections, steps, BCs and loads.
 *
 * Set naming is deliberately taken from the mesher (`<instance>_xmin`,
 * `<instance>_zmax`, `NALL`, `EALL`, ...) and written into the deck verbatim, so
 * the name a hand-reader finds in the .inp is exactly the name that
 * `abaqus_results` accepts. Regions that do not map to a mesher set get a fresh
 * `<load or boundary name>_N` set in the deck.
 */
import { num, textFile } from './util.js';
import { resolveRegion } from './mesh.js';

const NODE_FILE_VARS = new Set(['U', 'V', 'A', 'RF', 'RFL', 'NT', 'TS', 'PU']);
const EL_FILE_VARS = new Set(['S', 'E', 'ME', 'PEEQ', 'ENER', 'HFL', 'ERR']);

/** CalculiX reads free-format cards; 16 entries per line keeps them readable. */
function wrapIds(ids, perLine = 16) {
  const lines = [];
  for (let index = 0; index < ids.length; index += perLine) {
    lines.push(ids.slice(index, index + perLine).join(', '));
  }
  return lines.length > 0 ? lines : [''];
}

/** Group elements by part and element type so each group gets one section. */
function elementGroups(mesh) {
  const groups = new Map();
  for (const element of mesh.elements) {
    const key = `${element.part}|${element.type}`;
    if (!groups.has(key)) groups.set(key, { part: element.part, type: element.type, elements: [] });
    groups.get(key).elements.push(element);
  }
  return [...groups.values()];
}

const groupSetName = (group) => `${group.part}_${group.type}`;

/**
 * Build a CalculiX/Abaqus input deck from a normalised spec and its mesh.
 * @param {object} spec - normalised spec.
 * @param {object} mesh - result of `buildMesh`.
 * @returns {{inp: string, notes: string[], errors: string[]}}
 */
export function buildCalculixDeck(spec, mesh) {
  const lines = [];
  const notes = [...mesh.warnings];
  const errors = [];
  const usedNames = new Set();

  const uniqueName = (base) => {
    let candidate = String(base).replace(/[^A-Za-z0-9_-]+/g, '_').toUpperCase().slice(0, 56);
    if (candidate === '') candidate = 'SET';
    let suffix = 1;
    while (usedNames.has(candidate)) {
      suffix += 1;
      candidate = `${candidate}_${suffix}`.slice(0, 60);
    }
    usedNames.add(candidate);
    return candidate;
  };

  const instanceNameOf = (requested) => (mesh.instances.find((candidate) => candidate.name === requested) ?? mesh.instances[0])?.name;

  lines.push('*HEADING');
  lines.push(`${spec.title} [units: ${spec.units}] - generated by dsh-abaqus (calculix backend)`);
  lines.push('*NODE, NSET=NALL');
  for (const node of mesh.nodes) lines.push(`${node.id}, ${num(node.x)}, ${num(node.y)}, ${num(node.z)}`);

  const groups = elementGroups(mesh);
  for (const group of groups) {
    lines.push(`*ELEMENT, TYPE=${group.type}, ELSET=${groupSetName(group)}`);
    for (const element of group.elements) lines.push(`${element.id}, ${element.nodes.join(', ')}`);
  }

  // ---- the mesher's named sets: the shared vocabulary with abaqus_results ---
  for (const [setName, set] of Object.entries(mesh.sets)) {
    if (set.nodes.length > 0) {
      lines.push(`*NSET, NSET=${setName}`);
      lines.push(...wrapIds(set.nodes));
      usedNames.add(setName);
    }
    if (set.elements.length > 0) {
      lines.push(`*ELSET, ELSET=${setName}`);
      lines.push(...wrapIds(set.elements));
      usedNames.add(setName);
    }
  }

  /** The mesher set name a region maps to, when there is one. */
  const canonicalName = (region, instanceName) => {
    if (region.kind === 'plane' && (region.side === 'min' || region.side === 'max')) return `${instanceName}_${region.axis}${region.side}`;
    if (region.kind === 'set') return region.set;
    return undefined;
  };

  /** Reuse a canonical set, or write a new one for an ad-hoc region. */
  const emitNodeSet = (preferred, nodeIds) => {
    if (preferred !== undefined && usedNames.has(preferred)) return preferred;
    const fresh = uniqueName(preferred ?? 'REGION_N');
    lines.push(`*NSET, NSET=${fresh}`);
    lines.push(...wrapIds(nodeIds));
    return fresh;
  };

  const resolve = (region, instance, tag) => {
    const resolved = resolveRegion(region, mesh, instance);
    if (resolved.nodeIds.length === 0 && resolved.elementIds.length === 0) {
      errors.push(`${tag}: region "${resolved.label}" selected nothing on instance "${instance}"`);
    }
    return resolved;
  };

  const boundarySets = [];
  for (const boundary of spec.boundaries) {
    if (boundary.amplitude !== undefined) notes.push(`boundary ${boundary.name}: amplitude is not implemented and was ignored`);
    const resolved = resolve(boundary.region, boundary.instance, `boundary ${boundary.name}`);
    const setName = resolved.nodeIds.length === 0
      ? undefined
      : emitNodeSet(canonicalName(boundary.region, instanceNameOf(boundary.instance)) ?? `${boundary.name}_N`, resolved.nodeIds);
    boundarySets.push({ ...boundary, setName, nodeCount: resolved.nodeIds.length, label: resolved.label });
  }

  const loadSets = [];
  for (const load of spec.loads) {
    if (load.type === 'gravity') {
      if (!Object.values(spec.materials).some((material) => material.rho !== undefined)) {
        errors.push(`load ${load.name}: gravity needs a density on every material`);
      }
      loadSets.push({ ...load, setName: 'EALL' });
      continue;
    }
    if (load.type === 'traction') {
      errors.push(`load ${load.name}: the traction type is implemented only by the Abaqus backend; use concentrated or pressure with CalculiX`);
      continue;
    }
    const resolved = resolve(load.region, load.instance, `load ${load.name}`);
    if (load.type === 'pressure') {
      if (resolved.faces.length === 0) {
        errors.push(`load ${load.name}: region "${resolved.label}" has no element faces to pressurise`);
        continue;
      }
      // Pressure is written per element face, so the region needs no set of its own.
      loadSets.push({ ...load, resolved });
    } else {
      if (resolved.nodeIds.length === 0) continue;
      const setName = emitNodeSet(canonicalName(load.region, instanceNameOf(load.instance)) ?? `${load.name}_N`, resolved.nodeIds);
      loadSets.push({ ...load, setName, nodeCount: resolved.nodeIds.length, resolved });
    }
  }

  for (const group of groups) {
    const part = spec.parts.find((candidate) => candidate.name === group.part);
    const material = spec.materials[part.material];
    lines.push(`*SOLID SECTION, ELSET=${groupSetName(group)}, MATERIAL=${material.name}`);
  }
  for (const material of Object.values(spec.materials)) {
    lines.push(`*MATERIAL, NAME=${material.name}`);
    lines.push('*ELASTIC');
    lines.push(`${num(material.E)}, ${num(material.nu)}`);
    if (material.rho !== undefined) {
      lines.push('*DENSITY');
      lines.push(num(material.rho));
    }
    if (material.plastic.length > 0) {
      lines.push('*PLASTIC');
      for (const [yieldStress, plasticStrain] of material.plastic) lines.push(`${num(yieldStress)}, ${num(plasticStrain)}`);
    }
    if (material.expansion !== undefined) {
      lines.push('*EXPANSION');
      lines.push(num(material.expansion));
    }
    if (material.conductivity !== undefined) {
      lines.push('*CONDUCTIVITY');
      lines.push(num(material.conductivity));
    }
    if (material.specificHeat !== undefined) {
      lines.push('*SPECIFIC HEAT');
      lines.push(num(material.specificHeat));
    }
  }

  for (const [index, step] of spec.steps.entries()) {
    if (index > 0 && step.previous !== spec.steps[index - 1].name) {
      notes.push(`step ${step.name}: a CalculiX deck is sequential, so "previous" is implicit and the declared "${step.previous}" was ignored`);
    }
    lines.push(`** step ${step.name} (${step.type})`);
    lines.push(step.nlgeom ? '*STEP, NLGEOM' : '*STEP');
    if (step.type === 'static') {
      lines.push('*STATIC');
      lines.push(`${num(step.initialInc)}, ${num(step.period)}, ${num(step.minInc)}, ${num(step.maxInc)}`);
    } else if (step.type === 'dynamic') {
      lines.push('*DYNAMIC');
      lines.push(`${num(step.initialInc)}, ${num(step.period)}, ${num(step.minInc)}, ${num(step.maxInc)}`);
    } else if (step.type === 'freq') {
      lines.push('*FREQUENCY');
      lines.push(`${step.eigenvalues}`);
    } else if (step.type === 'buckle') {
      lines.push('*BUCKLE');
      lines.push(`${step.eigenvalues}`);
    }

    const stepBoundaries = boundarySets.filter((candidate) => candidate.step === step.name && candidate.setName !== undefined);
    if (stepBoundaries.length > 0) {
      lines.push('*BOUNDARY');
      for (const boundary of stepBoundaries) {
        const first = boundary.dof[0];
        const last = boundary.dof[boundary.dof.length - 1];
        const contiguous = boundary.dof.length === last - first + 1;
        if (contiguous) lines.push(`${boundary.setName}, ${first}, ${last}, ${num(boundary.value)}`);
        else for (const dof of boundary.dof) lines.push(`${boundary.setName}, ${dof}, ${dof}, ${num(boundary.value)}`);
      }
    }

    const stepLoads = loadSets.filter((candidate) => candidate.step === step.name);
    const concentrated = stepLoads.filter((load) => load.type === 'concentrated' && load.setName !== undefined);
    if (concentrated.length > 0) {
      lines.push('*CLOAD');
      for (const load of concentrated) {
        const perNode = load.total === false ? 1 : 1 / Math.max(1, load.nodeCount);
        const resultant = Math.hypot(...load.vector);
        notes.push(`load ${load.name}: resultant magnitude ${num(resultant)} spread evenly over ${load.nodeCount} nodes (${num(perNode * resultant)} each)`);
        for (const [component, dof] of [[0, 1], [1, 2], [2, 3]]) {
          if (load.vector[component] === 0) continue;
          lines.push(`${load.setName}, ${dof}, ${num(load.vector[component] * perNode)}`);
        }
      }
    }

    const distributed = stepLoads.filter((load) => load.type === 'pressure' || load.type === 'gravity');
    if (distributed.length > 0) {
      lines.push('*DLOAD');
      for (const load of distributed) {
        if (load.type === 'gravity') {
          const magnitude = Math.hypot(...load.vector);
          if (magnitude === 0) continue;
          const direction = load.vector.map((value) => value / magnitude);
          lines.push(`EALL, GRAV, ${num(magnitude)}, ${direction.map((value) => num(value)).join(', ')}`);
        } else {
          for (const face of load.resolved.faces) lines.push(`${face.elementId}, P${face.faceNumber}, ${num(load.value)}`);
        }
      }
    }

    const nodeVars = spec.output.fields.filter((field) => NODE_FILE_VARS.has(field));
    const elVars = spec.output.fields.filter((field) => EL_FILE_VARS.has(field));
    if (nodeVars.length > 0) {
      lines.push(`*NODE FILE, FREQUENCY=${spec.output.freq}`);
      lines.push(nodeVars.join(', '));
    }
    if (elVars.length > 0) {
      lines.push(`*EL FILE, FREQUENCY=${spec.output.freq}`);
      lines.push(elVars.join(', '));
    }
    const printSets = spec.writes.nodePrint.length > 0 ? spec.writes.nodePrint : (spec.writes.dat ? ['NALL'] : []);
    for (const setName of printSets) {
      lines.push(`*NODE PRINT, NSET=${setName}, TOTALS=YES`);
      lines.push('U, RF');
    }
    for (const setName of spec.writes.elPrint) {
      lines.push(`*EL PRINT, ELSET=${setName}, TOTALS=YES`);
      lines.push('S, E');
    }
    lines.push('*END STEP');
  }

  return { inp: textFile(lines), notes, errors };
}
