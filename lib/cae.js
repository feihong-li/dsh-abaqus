/**
 * Abaqus/CAE python generator.
 *
 * The script is run as `abaqus cae noGUI=build_<name>.py`: it builds real
 * geometry in the CAE kernel, meshes it with the CAE mesher, applies the same
 * steps/BCs/loads as the CalculiX deck and then calls `writeInput`, so the
 * solve step is identical on both backends (`abaqus job=` / `ccx -i`).
 *
 * The generated code stays Python 2/3 compatible on purpose: Abaqus releases
 * before 2023 embed Python 2.7, later ones embed Python 3.
 */
import { slugify } from './util.js';

/**
 * Render the CAE build script for a normalised spec.
 * @param {object} spec - normalised spec.
 * @param {{jobName: string}} options - the sanitised job/model name.
 * @returns {{script: string, notes: string[]}}
 */
export function buildCaeScript(spec, options) {
  const notes = [];
  const name = options.jobName;
  const payload = {
    name,
    title: spec.title,
    units: spec.units,
    materials: spec.materials,
    parts: spec.parts,
    instances: spec.instances,
    steps: spec.steps,
    boundaries: spec.boundaries,
    loads: spec.loads,
    mesh: { size: spec.mesh.size, element: spec.mesh.element ?? 'C3D8' },
    output: spec.output,
  };
  notes.push('the CAE backend meshes the real geometry, so `mesh.size` is a seed size and the element count may differ from the built-in mesher');
  if (spec.mesh.element === undefined) notes.push('mesh.element: defaulted to C3D8 for the CAE mesher');
  const elementConstant = spec.mesh.element ?? 'C3D8';

  // JSON string literal syntax is a valid subset of Python string syntax, so a
  // doubly-encoded JSON string can be pasted straight into the script.
  const literal = JSON.stringify(JSON.stringify(payload));

  const script = `# -*- coding: mbcs -*-
# Generated by dsh-abaqus. Builds ${name}, meshes it and writes the input deck.
from __future__ import print_function
import json
import sys
import traceback

from abaqus import *
from abaqusConstants import *
import mesh as meshModule
import regionToolset

SPEC = json.loads(${literal})
TOL_FRACTION = 1e-6
SETS = {}


def log(message):
    print('[dsh-abaqus] ' + message)


def instance_bounds(assembly, instance_name):
    corners = assembly.instances[instance_name].getBoundingBox()
    return corners


def tolerance(corners):
    diagonal = 0.0
    for axis in range(3):
        diagonal += (corners[1][axis] - corners[0][axis]) ** 2
    return max(1e-9, TOL_FRACTION * (diagonal ** 0.5))


def region_for(assembly, instance_name, region, tag):
    """Resolve a spec region to an assembly Set (which is also a Region)."""
    key = tag
    if key in SETS:
        return assembly.sets[SETS[key]]
    instance = assembly.instances[instance_name]
    corners = instance_bounds(assembly, instance_name)
    tol = tolerance(corners)
    if 'set' in region:
        return assembly.sets[region['set']]
    arguments = {}
    if 'plane' in region:
        axis = 'xyz'.index(region['axis'])
        if region['side'] == 'min':
            value = corners[0][axis]
        elif region['side'] == 'max':
            value = corners[1][axis]
        else:
            value = float(region['value'])
    elif 'bbox' in region:
        axis = None
        value = None
    else:
        raise RuntimeError('region for ' + tag + ' needs plane, bbox or set in the CAE backend')
    for index in range(3):
        letter = 'xyz'[index]
        if 'bbox' in region:
            low = region['bbox'].get(letter + 'Min')
            high = region['bbox'].get(letter + 'Max')
            arguments[letter + 'Min'] = corners[0][index] - tol if low is None else float(low) - tol
            arguments[letter + 'Max'] = corners[1][index] + tol if high is None else float(high) + tol
        elif index == axis:
            arguments[letter + 'Min'] = value - tol
            arguments[letter + 'Max'] = value + tol
        else:
            arguments[letter + 'Min'] = corners[0][index] - tol
            arguments[letter + 'Max'] = corners[1][index] + tol
    faces = instance.faces.getByBoundingBox(**arguments)
    if len(faces) == 0:
        raise RuntimeError('region ' + tag + ' selected no faces on instance ' + instance_name)
    set_name = 'SET_' + tag.replace('-', '_').replace('.', '_').upper()
    assembly.Set(name=set_name, faces=faces)
    SETS[key] = set_name
    log('region %s -> %d face(s) in %s' % (tag, len(faces), set_name))
    return assembly.sets[set_name]


def build_part(model, part):
    geometry = part['geometry']
    name = part['name']
    if geometry['kind'] == 'box':
        size = geometry['size']
        sketch = model.ConstrainedSketch(name='__profile_%s__' % name, sheetSize=2.0 * max(size))
        sketch.rectangle(point1=(0.0, 0.0), point2=(size[0], size[1]))
        created = model.Part(name=name, dimensionality=THREE_D, type=DEFORMABLE_BODY)
        created.BaseSolidExtrude(sketch=sketch, depth=size[2])
        del model.sketches['__profile_%s__' % name]
        return created
    if geometry['kind'] == 'cylinder':
        radius = geometry['radius']
        inner = geometry.get('innerRadius') or 0.0
        sketch = model.ConstrainedSketch(name='__profile_%s__' % name, sheetSize=4.0 * radius)
        sketch.CircleByCenterPerimeter(center=(0.0, 0.0), point1=(radius, 0.0))
        if inner > 0.0:
            sketch.CircleByCenterPerimeter(center=(0.0, 0.0), point1=(inner, 0.0))
        created = model.Part(name=name, dimensionality=THREE_D, type=DEFORMABLE_BODY)
        created.BaseSolidExtrude(sketch=sketch, depth=geometry['height'])
        del model.sketches['__profile_%s__' % name]
        return created
    raise RuntimeError('unsupported geometry kind ' + str(geometry['kind']))


def build():
    name = SPEC['name']
    model = mdb.Model(name=name)

    for material in SPEC['materials'].values():
        created = model.Material(name=material['name'])
        created.Elastic(table=((material['E'], material['nu']),))
        if material.get('rho') is not None:
            created.Density(table=((material['rho'],),))
        if material.get('plastic'):
            created.Plastic(table=tuple((row[0], row[1]) for row in material['plastic']))
        if material.get('expansion') is not None:
            created.Expansion(table=((material['expansion'],),))
        if material.get('conductivity') is not None:
            created.Conductivity(table=((material['conductivity'],),))
        if material.get('specificHeat') is not None:
            created.SpecificHeat(table=((material['specificHeat'],),))

    for part in SPEC['parts']:
        created = build_part(model, part)
        section = model.HomogeneousSolidSection(name='SEC_' + part['name'], material=part['material'])
        cells = created.cells
        created.SectionAssignment(region=(cells,), sectionName='SEC_' + part['name'], offset=0.0, offsetType=MIDDLE_SURFACE, thicknessAssignment=FROM_SECTION)

    assembly = model.rootAssembly
    assembly.DatumCsysByDefault(CARTESIAN)
    for instance in SPEC['instances']:
        part = None
        for candidate in SPEC['parts']:
            if candidate['name'] == instance['part']:
                part = candidate
        geometry = part['geometry']
        created = assembly.Instance(name=instance['name'], part=model.parts[instance['part']], dependent=ON)
        axis = geometry.get('axis', 'z') if geometry['kind'] == 'cylinder' else 'z'
        if axis == 'x':
            assembly.rotate(instanceList=(instance['name'],), axisPoint=(0.0, 0.0, 0.0), axisDirection=(0.0, 1.0, 0.0), angle=90.0)
        elif axis == 'y':
            assembly.rotate(instanceList=(instance['name'],), axisPoint=(0.0, 0.0, 0.0), axisDirection=(1.0, 0.0, 0.0), angle=-90.0)
        for index, axis_name in enumerate(('x', 'y', 'z')):
            angle = instance['rotate'][index]
            if abs(angle) > 1e-12:
                direction = [0.0, 0.0, 0.0]
                direction[index] = 1.0
                assembly.rotate(instanceList=(instance['name'],), axisPoint=(0.0, 0.0, 0.0), axisDirection=tuple(direction), angle=angle)
        if any(abs(value) > 1e-12 for value in instance['translate']):
            assembly.translate(instanceList=(instance['name'],), vector=tuple(instance['translate']))

    # ---- mesh ---------------------------------------------------------------
    element_code = SPEC['mesh']['element']
    for part in SPEC['parts']:
        created = model.parts[part['name']]
        geometry = part['geometry']
        created.seedPart(size=float(SPEC['mesh']['size']), deviationFactor=0.1, minSizeFactor=0.1)
        technique = STRUCTURED if geometry['kind'] == 'box' else SWEEP
        try:
            created.setMeshControls(regions=created.cells, elemShape=HEX, technique=technique)
        except Exception as error:
            log('mesh controls on %s fell back to the mesher default: %s' % (part['name'], error))
        try:
            created.setElementType(regions=(created.cells,), elemTypes=(meshModule.ElemType(elemCode=${elementConstant}, elemLibrary=STANDARD),))
        except Exception as error:
            raise RuntimeError('element type ' + element_code + ' is not available for ' + part['name'] + ': ' + str(error))
        created.generateMesh()
        log('meshed %s: %d nodes, %d elements' % (part['name'], len(created.nodes), len(created.elements)))

    # ---- steps --------------------------------------------------------------
    for index, step in enumerate(SPEC['steps']):
        previous = 'Initial' if index == 0 else SPEC['steps'][index - 1]['name']
        if step['type'] == 'static':
            model.StaticStep(name=step['name'], previous=previous, description=step.get('description', ''), timePeriod=step['period'], initialInc=step['initialInc'], minInc=step['minInc'], maxInc=step['maxInc'], nlgeom=ON if step['nlgeom'] else OFF)
        elif step['type'] == 'dynamic':
            model.ImplicitDynamicsStep(name=step['name'], previous=previous, description=step.get('description', ''), timePeriod=step['period'], initialInc=step['initialInc'], minInc=step['minInc'], maxInc=step['maxInc'], nlgeom=ON if step['nlgeom'] else OFF)
        elif step['type'] == 'freq':
            model.FrequencyStep(name=step['name'], previous=previous, description=step.get('description', ''), numEigen=int(step['eigenvalues']))
        elif step['type'] == 'buckle':
            model.BuckleStep(name=step['name'], previous=previous, description=step.get('description', ''), numEigen=int(step['eigenvalues']))

    first_step = SPEC['steps'][0]['name']
    try:
        model.fieldOutputRequests['F-Output-1'].setValues(variables=tuple(SPEC['output']['fields']), frequency=int(SPEC['output']['freq']))
    except KeyError:
        model.FieldOutputRequest(name='F-Output-1', createStepName=first_step, variables=tuple(SPEC['output']['fields']), frequency=int(SPEC['output']['freq']))

    # ---- boundary conditions ------------------------------------------------
    for index, boundary in enumerate(SPEC['boundaries']):
        region = region_for(assembly, boundary['instance'], boundary['region'], boundary['name'])
        arguments = {'name': boundary['name'], 'createStepName': boundary['step'], 'region': region}
        for position, dof in enumerate(boundary['dof']):
            arguments['u%d' % dof] = float(boundary['value'])
        model.DisplacementBC(distributionType=UNIFORM, **arguments)

    # ---- loads --------------------------------------------------------------
    for load in SPEC['loads']:
        if load['type'] == 'gravity':
            vector = load['vector']
            model.Gravity(name=load['name'], createStepName=load['step'], comp1=float(vector[0]), comp2=float(vector[1]), comp3=float(vector[2]), distributionType=UNIFORM)
            continue
        region = region_for(assembly, load['instance'], load['region'], load['name'])
        if load['type'] == 'concentrated':
            vector = load['vector']
            if load.get('total', True):
                count = max(1, len(assembly.sets[SETS[load['name']]].nodes))
                vector = [value / count for value in vector]
                log('load %s spread over %d nodes' % (load['name'], count))
            model.ConcentratedForce(name=load['name'], createStepName=load['step'], region=region, distributionType=UNIFORM, cf1=float(vector[0]), cf2=float(vector[1]), cf3=float(vector[2]))
        elif load['type'] == 'pressure':
            model.Pressure(name=load['name'], createStepName=load['step'], region=region, distributionType=UNIFORM, magnitude=float(load['value']))
        elif load['type'] == 'traction':
            vector = load['vector']
            magnitude = sum(value * value for value in vector) ** 0.5
            if magnitude == 0.0:
                continue
            direction = [value / magnitude for value in vector]
            model.SurfaceTraction(name=load['name'], createStepName=load['step'], region=region, magnitude=magnitude, directionVector=(tuple(direction),), distributionType=UNIFORM, traction=GENERAL)

    # ---- write the deck -----------------------------------------------------
    job = mdb.Job(name=name, model=name, description='dsh-abaqus', type=ANALYSIS, numCpus=1, numDomains=1, multiprocessingMode=DEFAULT, nodalOutputPrecision=SINGLE)
    job.writeInput(consistencyChecking=OFF)
    log('wrote %s.inp' % name)
    return model


def main():
    try:
        build()
    except Exception:
        traceback.print_exc()
        print('DSH_ABAQUS_FAILED')
        sys.exit(2)
    print('DSH_ABAQUS_OK')


main()
`;

  return { script, notes };
}

/** Abaqus-safe model/job name: identifier-like, not starting with a digit. */
export function caeJobName(rawName) {
  const slug = slugify(rawName, 'model').replace(/^[^A-Za-z]+/, '');
  return slug === '' ? 'model' : slug;
}
